    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String cargo = txtCargo.getText().trim();
        String salarioTexto = txtSalario.getText().trim();
        String departamento = txtDepartamento.getText().trim();
        
        if (nombre.isEmpty() || apellido.isEmpty()
                || cargo.isEmpty() || salarioTexto.isEmpty()
                || departamento.isEmpty()){
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }
        double salario;
        try{
            salario = Double.parseDouble(salarioTexto);
            if (salario < 0){
                JOptionPane.showMessageDialog(this, "El salario no puede ser negativo");
                return;
            }
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Ingrese un salario valido. Ejemplo: 25000.00");
                return;
        }
        Empleado emp = new Empleado();
        emp.setNombre(nombre);
        emp.setApellido(apellido);
        emp.setCargo(cargo);
        emp.setSalario(salario);
        emp.setDepartamento(departamento);
        
        EmpleadoDAO dao = new EmpleadoDAO();
        if(dao.insertar(emp)){
            JOptionPane.showMessageDialog(this,"Empleado registrado correctamente");
            limpiarCampos();
        }
    }//GEN-LAST:event_btnAceptarActionPerformed

