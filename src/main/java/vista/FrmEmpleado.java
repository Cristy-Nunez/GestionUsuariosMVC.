     private void cargarEmpleadosActivos(){
        try{
            EmpleadoDAO dao = new EmpleadoDAO();
            ArrayList<Empleado> lista = dao.listarActivos();
            
            jcbSeleccionEmpleado.removeAllItems();
            
            for(Empleado emp : lista){
                jcbSeleccionEmpleado.addItem(emp);
            }
            
            
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al cargar Empleados" + e.getMessage());
        }
    }
    private void mostrarDatosEnCampos(Empleado emp) {
       if (emp != null) {
        txtNombre.setText(emp.getNombre());
        txtApellido.setText(emp.getApellido());
        txtSalarioB.setText(String.valueOf(emp.getSalario()));
       }else {
        txtNombre.setText("");
        txtApellido.setText("");
        txtSalarioB.setText("");
    }
}
     
    

